-- 8. Investigation, resolution, closure, feedback and SLA early warnings
ALTER TABLE incidents
    ADD COLUMN awaiting_reporter_info BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN resolution_summary VARCHAR(2000),
    ADD COLUMN resolved_by VARCHAR(255),
    ADD COLUMN closed_at TIMESTAMP,
    ADD COLUMN feedback_rating INTEGER CHECK (feedback_rating BETWEEN 1 AND 5),
    ADD COLUMN feedback_comment VARCHAR(1000),
    ADD COLUMN feedback_at TIMESTAMP,
    ADD COLUMN response_warned BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN resolution_warned BOOLEAN NOT NULL DEFAULT FALSE;

-- 9. Incident conversation thread (investigation notes, information requests and replies)
CREATE TABLE incident_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    type VARCHAR(30) NOT NULL CHECK (type IN (
        'ADDITIONAL_INFO', 'INFO_RESPONSE', 'INFO_REQUEST', 'INVESTIGATION',
        'RESOLUTION', 'REOPEN_REASON', 'STATUS_COMMENT'
    )),
    author_name VARCHAR(255) NOT NULL,
    author_email VARCHAR(255) NOT NULL,
    author_role VARCHAR(20) NOT NULL,
    body VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_incident_notes_incident_id ON incident_notes (incident_id);
ALTER TABLE incident_notes ENABLE ROW LEVEL SECURITY;

-- 10. Automatic categorisation (Naive Bayes suggestion and the reporter's original choice)
ALTER TABLE incidents
    ADD COLUMN reported_category VARCHAR(40),
    ADD COLUMN suggested_category VARCHAR(40),
    ADD COLUMN classification_confidence DOUBLE PRECISION;
