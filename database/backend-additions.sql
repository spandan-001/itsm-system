-- Schema additions for the backend features on feature/incident-management
-- (SLA, audit trail, notifications, duplicates, technician skills, QUEUED).
-- Run after database/schema.sql. Column names match Hibernate's defaults,
-- so spring.jpa.hibernate.ddl-auto=validate passes.

-- 1. New lifecycle status
ALTER TABLE incidents DROP CONSTRAINT IF EXISTS incidents_status_check;
ALTER TABLE incidents ADD CONSTRAINT incidents_status_check CHECK (status IN (
    'NEW', 'CLASSIFIED', 'QUEUED', 'ASSIGNED', 'ACKNOWLEDGED',
    'IN_PROGRESS', 'RESOLVED', 'VERIFIED', 'CLOSED'
));

-- 2. SLA tracking and duplicate links on incidents
ALTER TABLE incidents
    ADD COLUMN response_due_at TIMESTAMP,
    ADD COLUMN resolution_due_at TIMESTAMP,
    ADD COLUMN responded_at TIMESTAMP,
    ADD COLUMN resolved_at TIMESTAMP,
    ADD COLUMN response_breached BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN resolution_breached BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN duplicate_of_id BIGINT REFERENCES incidents (id) ON DELETE SET NULL,
    ADD COLUMN duplicate_score DOUBLE PRECISION;

CREATE INDEX idx_incidents_duplicate_of_id ON incidents (duplicate_of_id);

-- 3. Technician skills (one row per category a technician can handle)
CREATE TABLE technician_skills (
    technician_id BIGINT NOT NULL REFERENCES technicians (id) ON DELETE CASCADE,
    skill VARCHAR(40) NOT NULL CHECK (skill IN (
        'HARDWARE', 'SOFTWARE', 'NETWORK', 'DATABASE',
        'CLOUD', 'SECURITY', 'AUTHENTICATION', 'APPLICATION', 'STORAGE'
    )),
    PRIMARY KEY (technician_id, skill)
);

-- 4. SLA policies (the app inserts defaults for P1-P4 on startup if missing)
CREATE TABLE sla_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    priority VARCHAR(10) NOT NULL UNIQUE CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    response_minutes BIGINT NOT NULL,
    resolution_minutes BIGINT NOT NULL
);

-- 5. Audit trail (append-only)
CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    action VARCHAR(30) NOT NULL,
    from_status VARCHAR(30),
    to_status VARCHAR(30),
    details VARCHAR(1000) NOT NULL,
    actor VARCHAR(255) NOT NULL,
    occurred_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_audit_logs_incident_id ON audit_logs (incident_id);

-- 6. Notifications (in-app inbox + simulated email log)
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_name VARCHAR(255) NOT NULL,
    recipient_email VARCHAR(255) NOT NULL,
    channel VARCHAR(20) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    incident_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_notifications_recipient ON notifications (recipient_email);

-- Spring owns authorization. Keep these tables closed to Supabase's public API roles.
ALTER TABLE technician_skills ENABLE ROW LEVEL SECURITY;
ALTER TABLE sla_policies ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;

-- 7. Existing seed technicians get their domain as a skill
INSERT INTO technician_skills (technician_id, skill)
SELECT id, domain FROM technicians
WHERE domain IN ('HARDWARE', 'SOFTWARE', 'NETWORK', 'DATABASE', 'CLOUD',
                 'SECURITY', 'AUTHENTICATION', 'APPLICATION', 'STORAGE')
ON CONFLICT DO NOTHING;

