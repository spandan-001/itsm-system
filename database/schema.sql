-- 1. employees
CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    department VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. technicians
CREATE TABLE technicians (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    domain VARCHAR(100) NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. it_services
CREATE TABLE it_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    criticality VARCHAR(20) NOT NULL CHECK (criticality IN ('LOW', 'MEDIUM', 'HIGH')),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 4. incidents
CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    category VARCHAR(40) NOT NULL CHECK (category IN (
        'HARDWARE', 'SOFTWARE', 'NETWORK', 'DATABASE',
        'CLOUD', 'SECURITY', 'AUTHENTICATION', 'APPLICATION', 'STORAGE'
    )),
    impact VARCHAR(20) NOT NULL CHECK (impact IN ('LOW', 'MEDIUM', 'HIGH')),
    urgency VARCHAR(20) NOT NULL CHECK (urgency IN ('LOW', 'MEDIUM', 'HIGH')),
    priority VARCHAR(10) NOT NULL CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    status VARCHAR(30) NOT NULL CHECK (status IN (
        'NEW', 'CLASSIFIED', 'ASSIGNED', 'ACKNOWLEDGED',
        'IN_PROGRESS', 'RESOLVED', 'VERIFIED', 'CLOSED'
    )),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reporter_id BIGINT NOT NULL,
    assigned_technician_id BIGINT,

    CONSTRAINT fk_incidents_reporter
        FOREIGN KEY (reporter_id) REFERENCES employees (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_incidents_assigned_technician
        FOREIGN KEY (assigned_technician_id) REFERENCES technicians (id)
        ON DELETE RESTRICT
);

-- 5. incident_services (many-to-many junction table)
CREATE TABLE incident_services (
    incident_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,

    CONSTRAINT pk_incident_services PRIMARY KEY (incident_id, service_id),

    CONSTRAINT fk_incident_services_incident
        FOREIGN KEY (incident_id) REFERENCES incidents (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_incident_services_service
        FOREIGN KEY (service_id) REFERENCES it_services (id)
        ON DELETE RESTRICT
);

-- Recommended indexes
CREATE INDEX idx_incidents_reporter_id ON incidents (reporter_id);
CREATE INDEX idx_incidents_assigned_technician_id ON incidents (assigned_technician_id);
CREATE INDEX idx_incidents_status ON incidents (status);
CREATE INDEX idx_incidents_priority ON incidents (priority);
CREATE INDEX idx_incident_services_service_id ON incident_services (service_id);